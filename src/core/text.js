export const LANGS = ['en', 'fil'];

/** A text in a language ('en' or 'fil'); the key itself if there is none. */
export function t(key, lang) {
  const v = STRINGS[key];
  return v ? v[lang === 'fil' ? 1 : 0] : key;
}

export const has = (key) => Object.prototype.hasOwnProperty.call(STRINGS, key);

/** A text with its blanks {0}, {1}... filled. */
export function format(key, lang, ...args) {
  return t(key, lang).replace(/\{(\d+)\}/g, (m, i) => (args[i] !== undefined ? String(args[i]) : m));
}

/** Puts names in the place of keys: "hazard.fire" becomes "the fire in the fallen house". */
export const names = (args, lang) => (args || []).map((a) => (typeof a === 'string' && has(a) ? t(a, lang) : a));

/** The words of a message of the rules: { kind, key, args }. */
export const say = (e, lang) => format(e.key, lang, ...names(e.args, lang));

/** Minutes and seconds, as 3:07 (seconds rounded as C# does, halves to even). */
export function clock(seconds) {
  const v = Math.max(0, seconds), f = Math.floor(v), r = v - f;
  const s = r > 0.5 ? f + 1 : r < 0.5 ? f : (f % 2 === 0 ? f : f + 1);
  return Math.floor(s / 60) + ':' + String(s % 60).padStart(2, '0');
}

/** The first letter as a capital: names start sentences. */
export const capital = (s) => (s ? s[0].toUpperCase() + s.slice(1) : s);

/** The name of the direction a heading points to: "north-west". */
export function direction(heading, lang) {
  const d = ((heading % 360) + 360 + 22.5) % 360;
  return t('dir.' + ['N', 'NE', 'E', 'SE', 'S', 'SW', 'W', 'NW'][Math.floor(d / 45) % 8], lang);
}
